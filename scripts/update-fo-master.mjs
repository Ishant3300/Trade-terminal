// Regenerates lib/terminal/fo-master.ts from NSE's F&O contract master.
//
//   npm run update:fo
//
// Downloads the latest NSE_FO_contract_DDMMYYYY.csv.gz (walking back from
// today until one exists) and writes every F&O symbol with its lot size and
// the exact futures / option expiry dates NSE lists (holiday shifts included).
// Run at least once a month so new expiries appear.

import { writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../lib/terminal/fo-master.ts", import.meta.url));
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36";
const MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"];
const pad = (n) => String(n).padStart(2, "0");

async function download() {
  for (let back = 0; back < 10; back++) {
    const d = new Date();
    d.setDate(d.getDate() - back);
    const stamp = `${pad(d.getDate())}${pad(d.getMonth() + 1)}${d.getFullYear()}`;
    const url = `https://nsearchives.nseindia.com/content/fo/NSE_FO_contract_${stamp}.csv.gz`;
    const res = await fetch(url, { headers: { "User-Agent": UA, Accept: "*/*" } });
    const buf = Buffer.from(await res.arrayBuffer());
    if (res.ok && buf[0] === 0x1f && buf[1] === 0x8b) {
      console.log(`Downloaded ${url}`);
      const iso = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
      return { csv: gunzipSync(buf).toString("utf8"), date: iso, file: url.split("/").pop() };
    }
    console.log(`Not available: ${stamp}`);
  }
  throw new Error("No NSE F&O contract master found in the last 10 days");
}

const { csv, date, file } = await download();

// Columns (by position; NSE's header names are offset by one):
// 2 = FUTIDX | FUTSTK | OPTIDX | OPTSTK, 3 = symbol, 4 = expiry (seconds since 1980-01-01), 8 = lot size
const EPOCH_1980 = Date.UTC(1980, 0, 1);
const lots = new Map();
const indices = new Set();
const fut = new Map();
const opt = new Map();

for (const line of csv.split("\n")) {
  const c = line.split(",");
  const kind = c[2];
  if (kind !== "FUTIDX" && kind !== "FUTSTK" && kind !== "OPTIDX" && kind !== "OPTSTK") continue;
  const symbol = c[3].trim();
  if (!symbol || /NSETEST$/.test(symbol)) continue;
  const lot = Number(c[8]);
  const exp = new Date(EPOCH_1980 + Number(c[4]) * 1000);
  const iso = `${exp.getUTCFullYear()}-${pad(exp.getUTCMonth() + 1)}-${pad(exp.getUTCDate())}`;
  if (lot > 0) lots.set(symbol, lot);
  if (kind.endsWith("IDX")) indices.add(symbol);
  const target = kind.startsWith("FUT") ? fut : opt;
  if (!target.has(symbol)) target.set(symbol, new Set());
  target.get(symbol).add(iso);
}

const symbols = [...lots.keys()].sort((a, b) => {
  const ai = indices.has(a), bi = indices.has(b);
  return ai !== bi ? (ai ? -1 : 1) : a.localeCompare(b);
});
const list = (m, s) => [...(m.get(s) ?? [])].sort();

// Most symbols share the same expiry calendar; store it once plus per-symbol exceptions.
const mostCommon = (m) => {
  const count = new Map();
  for (const s of symbols) {
    const k = JSON.stringify(list(m, s));
    count.set(k, (count.get(k) ?? 0) + 1);
  }
  return JSON.parse([...count].sort((a, b) => b[1] - a[1])[0][0]);
};
const defFut = mostCommon(fut);
const defOpt = mostCommon(opt);
const overrides = {};
for (const s of symbols) {
  const f = list(fut, s), o = list(opt, s);
  const entry = {};
  if (JSON.stringify(f) !== JSON.stringify(defFut)) entry.fut = f;
  if (JSON.stringify(o) !== JSON.stringify(defOpt)) entry.opt = o;
  if (Object.keys(entry).length) overrides[s] = entry;
}

const q = (s) => JSON.stringify(s);
const arr = (a) => `[${a.map(q).join(", ")}]`;
const lotLines = [];
for (let i = 0; i < symbols.length; i += 6) {
  lotLines.push("  " + symbols.slice(i, i + 6).map((s) => `${/^[A-Z_$][A-Z0-9_$]*$/.test(s) ? s : q(s)}: ${lots.get(s)}`).join(", ") + ",");
}
const ovLines = Object.entries(overrides).map(([s, e]) => {
  const parts = [];
  if (e.fut) parts.push(`fut: ${arr(e.fut)}`);
  if (e.opt) parts.push(`opt: ${arr(e.opt)}`);
  return `  ${/^[A-Z_$][A-Z0-9_$]*$/.test(s) ? s : q(s)}: { ${parts.join(", ")} },`;
});

const out = `// AUTO-GENERATED by scripts/update-fo-master.mjs — do not edit by hand.
// Source: NSE ${file} (${symbols.length} symbols). Run \`npm run update:fo\` to refresh.

export const FO_MASTER_DATE = ${q(date)};

/** Index underlyings (FUTIDX / OPTIDX); everything else is a stock. */
export const FO_INDICES: readonly string[] = ${arr([...indices].sort())};

/** Market lot per underlying. */
export const FO_LOTS: Record<string, number> = {
${lotLines.join("\n")}
};

/** Expiry calendar shared by most symbols (YYYY-MM-DD). */
export const FO_DEFAULT_EXPIRIES = {
  fut: ${arr(defFut)},
  opt: ${arr(defOpt)},
};

/** Symbols whose expiries differ from the default (e.g. NIFTY weeklies, long-dated options). */
export const FO_EXPIRY_OVERRIDES: Record<string, { fut?: string[]; opt?: string[] }> = {
${ovLines.join("\n")}
};
`;

writeFileSync(OUT, out);
console.log(`Wrote ${OUT}: ${symbols.length} symbols (${indices.size} indices), ${Object.keys(overrides).length} with custom expiries`);
console.log(`Default futures expiries: ${defFut.map((d) => { const [y, m, dd] = d.split("-"); return `${dd}${MONTHS[m - 1]}${y}`; }).join(", ")}`);
